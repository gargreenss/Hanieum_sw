client = anthropic.Anthropic()


# ============================================================
# 이미지 인코딩
# ============================================================

def encode_image(img: Image.Image) -> str:

    img = img.convert("RGB")

    img.thumbnail(
        (MAX_SIZE, MAX_SIZE)
    )

    buf = io.BytesIO()

    img.save(
        buf,
        format="JPEG",
        quality=85
    )

    return base64.standard_b64encode(
        buf.getvalue()
    ).decode()


# ============================================================
# Claude 출력 정리
# ============================================================

def normalize_food(text: str) -> str:

    text = text.strip()

    # Claude가 가끔 붙이는 마크다운 제거
    text = text.replace("*", "")
    text = text.replace("`", "")
    text = text.replace('"', "")
    text = text.replace("'", "")

    text = text.strip()

    # 느린 모드에서 "최종답:" 파싱
    m = re.search(
        r"최종답\s*[:：]\s*(.+)",
        text
    )

    if m:
        text = m.group(1).strip()

    # 마지막 마침표 등 제거
    text = text.rstrip(
        ".。!！"
    ).strip()

    # 정확한 이름이면 바로 반환
    if text in VALID_FOODS:
        return text

    # 혹시 "답: 김치" 같은 형태가 나와도
    # 단 하나의 음식명만 포함된 경우 복구
    found = []

    for food in VALID_FOODS:
        if food in text:
            found.append(food)

    if len(found) == 1:
        return found[0]

    return "알 수 없는 음식"


# ============================================================
# 음식 판별
# ============================================================

def recognize_food(img: Image.Image) -> dict:

    msg = client.messages.create(
        model=MODEL,
        max_tokens=MAX_TOKENS,


        messages=[
            {
                "role": "user",
                "content": [
                    {
                        "type": "image",
                        "source": {
                            "type": "base64",
                            "media_type": "image/jpeg",
                            "data": encode_image(img)
                        }
                    },
                    {
                        "type": "text",
                        "text": PROMPT
                    }
                ]
            }
        ]
    )

    full = msg.content[0].text

    food = normalize_food(full)

    if food == "알 수 없는 음식" and full.strip() not in VALID_FOODS:
        print(
            f"[판별] 비정상/불확실 응답: "
            f"'{full.strip()}' → 알 수 없는 음식"
        )

    return {
        "food": food,
        "raw": full,
        "input_tokens": msg.usage.input_tokens,
        "output_tokens": msg.usage.output_tokens,
    }
